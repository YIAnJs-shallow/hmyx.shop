const fs = require('fs');
const path = require('path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const state = JSON.parse(fs.readFileSync(path.join(__dirname,'state.json'),'utf8'));
(async () => {
  const browser = await chromium.launch({headless:true,channel:'msedge'});
  const page = await browser.newPage({viewport:{width:1280,height:900}});
  const errors = [];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8099/user_login.php');
  await page.locator('[name=username]').fill('qa_buyer');
  await page.locator('[name=password]').fill('TestShop2026!');
  await Promise.all([page.waitForURL('**/user_center.php'),page.locator('form button[type=submit]').click()]);
  await page.goto('http://127.0.0.1:8099/detail.php?id='+state.platform_product);
  await page.getByRole('heading',{name:'平台测试商品',exact:true}).first().waitFor();
  const output = process.env.SHOP_SCREENSHOT_DIR;
  if(output) await page.screenshot({path:path.join(output,'shop-detail-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'立即购买',exact:true}).click();
  await page.getByRole('heading',{name:'确认订单',exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)) throw new Error('Checkout overflows mobile viewport');
  if(output) await page.screenshot({path:path.join(output,'shop-checkout-mobile.png'),fullPage:true});
  await page.goto('http://127.0.0.1:8099/my_orders.php');
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)) throw new Error('Orders overflow mobile viewport');
  if(output) await page.screenshot({path:path.join(output,'shop-orders-mobile.png'),fullPage:true});
  await browser.close();
  if(errors.length) throw new Error(errors.join('\n'));
  console.log('Browser login, buy-now navigation, desktop rendering and mobile layouts passed.');
})().catch(e=>{console.error(e);process.exit(1)});
